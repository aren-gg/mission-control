def ascii_text(value):
    replacements = {'\u2014':' - ', '\u2013':'-', '\u2018':"'", '\u2019':"'", '\u201c':'"', '\u201d':'"', '\u2026':'...', '\u00b7':' / ', '\u2192':'->'}
    text = str(value)
    for old, new in replacements.items(): text = text.replace(old, new)
    return ''.join(c if 32 <= ord(c) <= 126 or c in '\n\t' else '?' for c in text)

def text_width(value):
    return sum(len(GLYPHS.get(c, GLYPHS['?'])[0])+1 for c in ascii_text(value).upper())

def pixel_text(painter, value, x, y, color=14):
    x, y = round(x), round(y)
    for ch in ascii_text(value).upper():
        glyph = GLYPHS.get(ch, GLYPHS['?'])
        for row, cells in enumerate(glyph):
            for col, pixel in enumerate(cells):
                if pixel == '1': painter.fillRect(x+col, y+row, 1, 1, COLORS[color])
        x += len(glyph[0])+1

_CACHE = {}
def whale_image(species='blue_whale', state='idle', frame=0, flip=False):
    key = (species, state, frame % 2, flip)
    if key in _CACHE: return _CACHE[key]
    pixels = [[-1]*64 for _ in range(32)]
    mask = set()
    def oval(cx,cy,rx,ry):
        for y in range(32):
            for x in range(64):
                if ((x-cx)/rx)**2+((y-cy)/ry)**2 <= 1: mask.add((x,y))
    def poly(points):
        for y in range(32):
            for x in range(64):
                hit = False
                j = len(points)-1
                for i,(xi,yi) in enumerate(points):
                    xj,yj = points[j]
                    if (yi>y)!=(yj>y) and x < (xj-xi)*(y-yi)/(yj-yi)+xi: hit=not hit
                    j=i
                if hit: mask.add((x,y))
    if species == 'beluga':
        oval(36,18,20,10); oval(48,11,9,8); oval(55,18,7,4)
    elif species == 'sperm_whale':
        oval(31,18,22,9); poly([(38,5),(59,5),(61,8),(61,25),(56,27),(36,25)])
    else:
        oval(35,17,25 if species=='blue_whale' else 23,9 if species=='blue_whale' else 10)
        if species == 'orca': poly([(28,11),(31,0),(35,3),(38,13)])
        elif species == 'humpback': poly([(28,10),(31,5),(36,12)])
        else: poly([(27,11),(30,7),(34,11)])
    poly([(5,14),(22,14),(23,22),(5,21)])
    offset = -2 if frame % 2 else 2
    poly([(1,8+offset),(7,11+offset),(12,18),(7,24+offset),(1,27+offset),(3,18)])
    poly([(33,21),(37,21),(34,29),(29,28),(29,25)])
    if species == 'humpback': poly([(34,20),(39,22),(31,31),(25,30)])
    if species == 'narwhal': poly([(56,12),(64,9),(63,12),(57,15)])
    body = 14 if species=='beluga' else 1 if species=='orca' else 2
    for x,y in mask:
        pixels[y][x] = body if all((x+dx,y+dy) in mask for dx,dy in ((1,0),(-1,0),(0,1),(0,-1))) else 0
    def rect(x,y,w,h,col):
        for yy in range(y,min(y+h,32)):
            for xx in range(x,min(x+w,64)):
                if (xx,yy) in mask and pixels[yy][xx] != 0: pixels[yy][xx]=col
    if species == 'blue_whale':
        rect(19,22,35,3,13)
        for x in (25,30,35,40,45): rect(x,23,1,2,2)
        for x,y in ((24,14),(37,12),(43,15),(30,17)): rect(x,y,3,1,13)
